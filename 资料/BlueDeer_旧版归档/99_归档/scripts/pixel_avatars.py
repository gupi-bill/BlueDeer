def render(species: str, rows: list[str]) -> Image.Image:
    """把 32x32 字符网格渲染成 128x128 PNG（最近邻放大，硬像素）。"""
    if len(rows) != GRID_SIZE:
        raise ValueError(f"{species}: 需要 {GRID_SIZE} 行，实际 {len(rows)}")
    canvas = Image.new("RGBA", (GRID_SIZE, GRID_SIZE), (0, 0, 0, 0))
    for y, row in enumerate(rows):
        row = row.rstrip(".").ljust(GRID_SIZE, ".")[:GRID_SIZE]
        for x, ch in enumerate(row):
            if ch not in PALETTE:
                raise ValueError(f"{species}: 未知字符 {ch!r} @ ({x},{y})")
            canvas.putpixel((x, y), PALETTE[ch])
    return canvas.resize(
        (GRID_SIZE * SCALE, GRID_SIZE * SCALE), Image.Resampling.NEAREST
    )


def main() -> int:
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out_dir = os.path.join(root, "static", "sprites")
    os.makedirs(out_dir, exist_ok=True)
    for species, rows in GRIDS.items():
        img = render(species, rows)
        path = os.path.join(out_dir, f"{species}.png")
        img.save(path)
        print(f"  [OK] {species}.png -> {path} ({img.size[0]}x{img.size[1]})")
    print(f"共 {len(GRIDS)} 个头像已生成到 static/sprites/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
